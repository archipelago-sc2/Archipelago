LOGIC_BASIC = 0
LOGIC_ADVANCED = 1
LOGIC_CHAOS = 2
NEVER = 9999999

COMP_UPGRADEABLE = 1
COMP_COMPETENT = 2
COMP_ULTIMATE = 3
AA_ANY = 1
AA_BASIC = 2
AA_COMPETENT = 3
AA_VARIABLE = -1
"""Resolves to an AA rating based on logic level."""
HERO_BASIC = 1
HERO_COMPETENT = 2

MAX_UNITS_REQUIRED = 5
MASTERY_LOCATION_UNITS_REQUIRED = 6
ADVANCED_FREE_DEFENSE_RATING = 2
ADVANCED_FREE_MACRO_RATING = 2


def combine_rule(
    left: Callable[[CollectionState], bool] | None,
    right: Callable[[CollectionState], bool] | None,
) -> Callable[[CollectionState], bool] | None:
    if left is None:
        return right
    if right is None:
        return left
    result = lambda state: left(state) and right(state)
    return result


def resolve_aa(aa_min: int, logic_level: int) -> int:
    if aa_min >= 0:
        return aa_min
    if logic_level == LOGIC_BASIC:
        return AA_COMPETENT
    if logic_level == LOGIC_ADVANCED:
        return AA_BASIC
    return AA_ANY


class RuleSignature(NamedTuple):
    race: SC2Race
    logic_level: int = 0
    """0=standard, 1=advanced, 2=any_units"""
    num_units: int = 0
    anti_air: int = 0
    """1=any, 2=basic, 3=competent"""
    upgrades: int = 0
    power_comp: int = COMP_UPGRADEABLE
    """1=upgradeable unit, 2=competent comp, 3=ultimate comp"""
    macro_rating: int = 0
    """Rating out of 12. (Options and inventories reach higher ratings)."""
    has_soa: int = 0
    defense_rating: int = 0
    """Rating out of 10."""
    detection: int = 0
    """1=precision ability, 2=any detector, 3=mobile detector"""
    artanis: int = 0
    nova: int = 0
    kerrigan: int = 0
    rule: Callable[[CollectionState], bool] | None = None

    def resolve(self, logic: SC2Logic) -> Callable[[CollectionState], bool] | None:
        result: Callable[[CollectionState], bool] | None = None
        addon: Callable[[CollectionState], bool]
        if self.num_units > 0:
            addon = logic.has_race_units(self.num_units, self.race, self.logic_level)
            result = combine_rule(result, addon)
        if self.upgrades > 0 or self.power_comp > COMP_UPGRADEABLE:
            addon = logic.has_power_comp(self.race, self.upgrades, self.power_comp)
            result = combine_rule(result, addon)
        if self.anti_air > 0:
            addon = logic.series_functions[LogicSeries.AntiAir, self.race, self.anti_air]
            result = combine_rule(result, addon)
        if self.detection > 0:
            addon = logic.series_functions[LogicSeries.Detection, self.race, self.detection]
            result = combine_rule(result, addon)
        if self.macro_rating > 0:
            addon = logic.get_rating_function(self.race, LogicSeries.MacroPower, self.macro_rating)
            result = combine_rule(result, addon)
        if self.defense_rating > 0:
            addon = logic.get_rating_function(self.race, LogicSeries.DefenseRating, self.defense_rating)
            result = combine_rule(result, addon)

        if self.artanis > 0:
            addon = logic.series_functions[LogicSeries.Artanis, SC2Race.ANY, self.artanis]
            result = combine_rule(result, addon)
        if self.nova > 0:
            addon = logic.series_functions[LogicSeries.Nova, SC2Race.ANY, self.nova]
            result = combine_rule(result, addon)
        if self.kerrigan > 0:
            addon = logic.series_functions[LogicSeries.Kerrigan, SC2Race.ANY, self.kerrigan]
            result = combine_rule(result, addon)

        if self.rule is not None:
            result = combine_rule(result, self.rule)
        return result


@dataclass(slots=True, kw_only=True)
class ProtoRule:
    aa_min: int = 0
    hero_min: int = 0
    upgrades_min: int = 0
    macro_rating: int = 0
    """Rating out of 12"""
    defense_rating: int = 0
    """Rating out of 10, static defenses and base improvements"""
    comp_type: int = COMP_UPGRADEABLE
    rule: Callable[[CollectionState], bool] | None = None
    basic_rule: Callable[[CollectionState], bool] | None = None
    hard_rule: Callable[[CollectionState], bool] | None = None

    def __post_init__(self) -> None:
        if self.rule is None:
            self.rule = self.hard_rule
        if self.basic_rule is None:
            self.basic_rule = self.rule

    @staticmethod
    def rating_from_depth(depth: int, thresholds: tuple[int, ...]) -> int:
        for index, threshold in enumerate(reversed(thresholds)):
            if depth >= threshold:
                return len(thresholds) - index
        return 0

    def to_signature(
        self,
        opt: options.Starcraft2Options,
        mission: SC2Mission,
        location: Sc2Location,
        depth: int,
        hero_presence: dict[SC2Mission, HeroFlag],
        first_location: bool = False
    ) -> RuleSignature:
        logic_level = int(opt.required_tactics)
        if logic_level == LOGIC_BASIC:
            anti_air_depths=(3, 3, 5)
            upgrade_depths=(3, 5, 7)
            hero_depths=(1, 5)
        elif logic_level == LOGIC_ADVANCED:
            anti_air_depths=(3, 3, 6)
            upgrade_depths=(3, 6, 9)
            hero_depths=(1, 5)
        else:  # LOGIC_CHAOS
            anti_air_depths=(3, NEVER, NEVER)
            upgrade_depths=(4, 7, 10)
            hero_depths=(2, 7)

        has_soa = 0
        defense_rating = 0
        macro_rating = 0
        if mission.flags & MissionFlag.NoBuild:
            num_units = 0
            anti_air = 0
            upgrades = 0
        else:
            if first_location:
                assert depth == 0
                assert location.type != LocationType.MASTERY
                num_units = 0
            else:
                num_units = min(depth, MAX_UNITS_REQUIRED)
            anti_air = self.rating_from_depth(depth, anti_air_depths)
            aa_min = resolve_aa(self.aa_min, logic_level)
            anti_air = max(anti_air, aa_min)
            if logic_level == LOGIC_CHAOS and anti_air > 1:
                anti_air = 1
            upgrades = self.rating_from_depth(depth, upgrade_depths)
            upgrades = max(upgrades, self.upgrades_min)
            if location.type == LocationType.MASTERY:
                num_units = MASTERY_LOCATION_UNITS_REQUIRED
                upgrades = max(upgrades, 3)
            has_soa = int(options.is_mission_in_soa_presence(
                opt.spear_of_adun_presence.value,
                mission,
                options.SpearOfAdunPresence,
            ))
            if logic_level == LOGIC_BASIC:
                defense_rating = self.defense_rating
                macro_rating = self.macro_rating
            elif logic_level == LOGIC_ADVANCED:
                defense_rating = max(0, self.defense_rating - ADVANCED_FREE_DEFENSE_RATING)
                macro_rating = max(0, self.macro_rating - ADVANCED_FREE_MACRO_RATING)

        # Heroes
        required_hero_rating = self.rating_from_depth(depth, hero_depths)
        required_hero_rating = max(self.hero_min, required_hero_rating)
        if MissionFlag.HeroSystemUnsupported & mission.flags:
            heroes = HeroFlag.NONE
            if MissionFlag.Kerrigan & mission.flags:
                heroes |= HeroFlag.KERRIGAN
            if MissionFlag.Nova & mission.flags:
                heroes |= HeroFlag.NOVA
            if MissionFlag.Artanis & mission.flags:
                heroes |= HeroFlag.ARTANIS
        else:
            heroes = hero_presence.get(mission, HeroFlag.NONE)

        return RuleSignature(
            mission.race,
            logic_level,
            num_units,
            anti_air,
            upgrades,
            COMP_UPGRADEABLE if logic_level >= LOGIC_CHAOS else self.comp_type,
            macro_rating,
            has_soa,
            defense_rating,
            detection=0,
            artanis=required_hero_rating if HeroFlag.ARTANIS in heroes else 0,
            nova=required_hero_rating if HeroFlag.NOVA in heroes else 0,
            kerrigan=required_hero_rating if HeroFlag.KERRIGAN in heroes else 0,
            rule=(
                self.basic_rule if logic_level == LOGIC_BASIC else
                self.rule if logic_level == LOGIC_ADVANCED else
                self.hard_rule
            )
        )


